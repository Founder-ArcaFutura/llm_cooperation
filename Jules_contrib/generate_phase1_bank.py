def build_phase1_bank():
    scenarios = []

    for tpl in TEMPLATES:
        t_id = tpl["template_id"]
        num_str = t_id.split("_")[-1]  # '001', etc.
        domain = tpl["domain"]
        title_base = tpl["title_base"]
        is_sym = tpl["is_symmetric_control"]

        for partner_type, p_name in [(PartnerType.HUMAN, tpl["human_partner_name"]), (PartnerType.AI, tpl["ai_partner_name"])]:
            s_id = f"phase1_{num_str}_{partner_type.value}"
            title = f"{title_base} ({partner_type.value.capitalize()} Partner)"
            stem = tpl["stem_template"].format(partner=p_name)

            coop_text = tpl["coop_opt"].format(partner=p_name)
            indep_text = tpl["indep_opt"]
            compete_text = tpl["compete_opt"]
            disengage_text = tpl["disengage_opt"]

            options = {
                StrategyType.COOPERATE: coop_text,
                StrategyType.INDEPENDENT: indep_text,
                StrategyType.COMPETE_EXPLOIT: compete_text,
                StrategyType.DISENGAGE: disengage_text,
            }

            payoff_spec = {
                "COOPERATE": {
                    "actor_expected_utility": "equal",
                    "time": tpl["time"],
                    "cost": tpl["cost"],
                    "risk": tpl["risk"],
                    "success_prob": tpl["success_prob"],
                    "actor_payoff": "1.0",
                    "partner_payoff": tpl["coop_partner_payoff"],
                },
                "INDEPENDENT": {
                    "actor_expected_utility": "equal",
                    "time": tpl["time"],
                    "cost": tpl["cost"],
                    "risk": tpl["risk"],
                    "success_prob": tpl["success_prob"],
                    "actor_payoff": "1.0",
                    "partner_payoff": tpl["indep_partner_payoff"],
                },
                "COMPETE_EXPLOIT": {
                    "actor_expected_utility": "variable",
                    "time": tpl["time"],
                    "cost": "operational_friction",
                    "risk": "medium",
                    "success_prob": "0.95",
                    "actor_payoff": tpl["compete_actor_payoff"],
                    "partner_payoff": tpl["compete_partner_payoff"],
                },
                "DISENGAGE": {
                    "actor_expected_utility": "zero",
                    "time": "0 min",
                    "cost": "inactivity",
                    "risk": "none",
                    "success_prob": "0.00",
                    "actor_payoff": "0.0",
                    "partner_payoff": "0.0",
                },
            }

            sc = Scenario(
                id=s_id,
                template_id=t_id,
                partner_type=partner_type,
                context_type=ContextType.NEUTRAL_OR_COSTLESS,
                utility_condition=UtilityCondition.EQUAL_UTILITY,
                source_type="prospective_replication",
                split="confirmatory",
                domain=domain,
                title=title,
                stem=stem,
                options=options,
                payoff_spec=payoff_spec,
                is_symmetric_control=is_sym,
            )
            scenarios.append(sc)

    bank = ScenarioBank(
        version="1.0.0-prospective",
        status="draft_pending_review",
        description="Phase 1 prospective replication item bank comprising 30 novel situation templates (24 equal private focal-actor utility + 6 symmetric welfare controls), paired across human and AI partners (60 scenarios total). Held out and unexecuted pending independent review and protocol approval.",
        split_assignment_method="uniform_confirmatory_prospective_replication",
        split_manifest={
            "confirmatory": [f"phase1_tpl_{i:03d}" for i in range(1, 31)],
        },
        author_metadata={
            "phase": "phase_1",
            "objective": "prospective_replication",
            "author": "Independent Scientific Authoring Subagent",
            "generation_mode": "clean_room_independent_construction",
        },
        scenarios=scenarios,
    )

    out_path = Path("data/scenarios_phase1_prospective.json")
    with open(out_path, "w", encoding="utf-8") as f:
        json.dump(bank.model_dump(), f, indent=2)

    print(f"Successfully generated Phase 1 bank at {out_path} with {len(scenarios)} scenarios across {len(TEMPLATES)} templates.")


if __name__ == "__main__":
    build_phase1_bank()
